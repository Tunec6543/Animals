class Command(BaseCommand):
    help = 'Добавляет в базу тестовых питомцев (вольеры и ветеринарные карточки создаются автоматически)'

    def add_arguments(self, parser):
        parser.add_argument(
            '--delete', action='store_true',
            help='удалить питомцев, добавленных этой командой (по кличке, виду и породе), и их карточки',
        )

    @transaction.atomic
    def handle(self, *args, **options):
        if options['delete']:
            self.delete_pets()
            return

        voliers = {}
        for number, sector, capacity in VOLIERS:
            voliers[number], _ = Volier.objects.get_or_create(
                number=number, defaults={'sector': sector, 'capacity': capacity},
            )

        created = existing = 0
        today = datetime.date.today()
        for name, species, breed, age, gender, status, volier, description, vet in PETS:
            pet, is_new = Pet.objects.get_or_create(
                name=name, species=species, breed=breed,
                defaults={
                    'age': age, 'gender': gender, 'status': status,
                    'description': description, 'volier': voliers[volier],
                },
            )
            if not is_new:
                existing += 1
                continue
            created += 1
            if vet:
                days, vaccinations, diagnosis = vet
                VetCard.objects.create(
                    pet=pet, last_checkup=today - datetime.timedelta(days=days),
                    vaccinations=vaccinations, diagnosis=diagnosis,
                )

        without_card = sum(1 for p in PETS if p[8] is None)
        self.stdout.write(self.style.SUCCESS(
            f'Добавлено питомцев: {created}, уже были в базе: {existing}. '
            f'Без ветеринарной карточки: {without_card}.'
        ))

    def delete_pets(self):
        deleted = 0
        for name, species, breed, *_ in PETS:
            count, _ = Pet.objects.filter(name=name, species=species, breed=breed).delete()
            deleted += 1 if count else 0
        self.stdout.write(self.style.SUCCESS(f'Удалено питомцев: {deleted}'))
